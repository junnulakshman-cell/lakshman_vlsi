// ============================================================================
// File: Memory_Burst_Transaction.sv
// Purpose:
//   Demonstrate SystemVerilog Constraint Random Verification (CRV) for a
//   memory-burst transaction array, followed by controlled post-randomization
//   error injection.
//
// Overview:
//   - Generate exactly 16 legal baseline transactions.
//   - Constrain address, burst length, beat size, alignment, and memory boundary.
//   - Require selected burst-length categories to appear in each randomization.
//   - Randomly select a fault mode using weighted distribution.
//   - Copy legal values into invalid_* drive arrays and inject one error there.
//   - Print baseline and injected values and count fault modes across runs.
//
// Important:
//   This is a stimulus-generation / self-checking example. A complete DUT
//   testbench should drive invalid_* values to the DUT and check the DUT's
//   response. The class's PASS messages only indicate stimulus checks.
// ============================================================================

typedef enum logic [2:0] {
  BAD_ADDRESS,  // Encoding 0: inject an out-of-range starting address
  BAD_BURST,    // Encoding 1: inject an unsupported burst length
  BAD_BEAT,     // Encoding 2: inject an unsupported beat size
  NO_ERROR      // Encoding 3: keep the legal baseline transaction unchanged
} mode_type;


class Memory_Burst_Transaction;

  // --------------------------------------------------------------------------
  // Randomized baseline fields.
  //
  // These arrays contain the values generated by the constraint solver.
  // They are intended to remain legal, even when a fault is selected.
  // --------------------------------------------------------------------------
  rand int unsigned start_addr[];
  rand int unsigned burst_len[];
  rand int unsigned beat_size[];

  // --------------------------------------------------------------------------
  // Post-randomization drive fields.
  //
  // These arrays are NOT rand. They are copied from the legal baseline fields
  // and then optionally modified in post_randomize().
  //
  // The constructor allocates them because they are dynamic arrays that are
  // written by procedural code rather than sized by random constraints.
  // --------------------------------------------------------------------------
  int unsigned invalid_start_addr[];
  int unsigned invalid_burst_len[];
  int unsigned invalid_beat_size[];

  // One fault mode per transaction.
  rand mode_type fault[];

  // Retained as a user-defined scenario variable. It is not used by the
  // current constraints or checks; it may be used for scenario control later.
  int scenario;


  // --------------------------------------------------------------------------
  // Constructor
  //
  // Allocate the non-random drive arrays to 16 elements. The randomized arrays
  // and fault array are sized by the dynamic_array constraint during randomize.
  // --------------------------------------------------------------------------
  function new();
    invalid_start_addr = new[16];
    invalid_burst_len  = new[16];
    invalid_beat_size  = new[16];
  endfunction


  // --------------------------------------------------------------------------
  // Constraint 1: exactly 16 transactions
  //
  // All randomized arrays have the same size. The same index across arrays
  // represents one transaction.
  // --------------------------------------------------------------------------
  constraint dynamic_array {
    start_addr.size() == 16;
    burst_len.size()  == 16;
    beat_size.size()  == 16;
    fault.size()      == 16;
  }


  // --------------------------------------------------------------------------
  // Constraint 2: legal starting address
  //
  // The memory contains 4096 bytes, so valid byte addresses are 0 through 4095.
  // --------------------------------------------------------------------------
  constraint addr_range {
    foreach (start_addr[i])
      start_addr[i] inside {[0:4095]};
  }


  // --------------------------------------------------------------------------
  // Constraint 3: legal burst lengths
  //
  // The transaction may transfer 1, 2, 4, 8, or 16 beats.
  // --------------------------------------------------------------------------
  constraint burst_range {
    foreach (burst_len[i])
      burst_len[i] inside {1, 2, 4, 8, 16};
  }


  // --------------------------------------------------------------------------
  // Constraint 4: legal beat sizes
  //
  // Beat size is measured in bytes and must be 1, 2, or 4.
  // --------------------------------------------------------------------------
  constraint beat_range {
    foreach (beat_size[i])
      beat_size[i] inside {1, 2, 4};
  }


  // --------------------------------------------------------------------------
  // Constraint 5: address alignment
  //
  // The starting address must be divisible by the beat size.
  // Example: a 4-byte beat requires an address divisible by 4.
  // --------------------------------------------------------------------------
  constraint addr_alignment {
    foreach (start_addr[i])
      start_addr[i] % beat_size[i] == 0;
  }


  // --------------------------------------------------------------------------
  // Constraint 6: memory boundary
  //
  // start_addr + transfer_size is the exclusive end address.
  // A value of 4096 is legal because the last accessed byte is 4095.
  // --------------------------------------------------------------------------
  constraint burst_boundary {
    foreach (start_addr[i])
      start_addr[i] + (burst_len[i] * beat_size[i]) <= 4096;
  }


  // --------------------------------------------------------------------------
  // Constraint 7: required burst-length categories
  //
  // Array reduction .sum() adds the expression for every array item.
  // int'(boolean_expression) converts each true result to integer 1 and false
  // to integer 0. Therefore, each sum counts matching burst lengths.
  //
  // Required in every randomization:
  //   - at least one burst of length 1
  //   - at least one burst of length 2 OR 4
  //   - at least one burst of length 8
  //   - at least one burst of length 16
  //
  // This does not separately require both length 2 and length 4.
  // --------------------------------------------------------------------------
  constraint burst_length_coverage {
    burst_len.sum() with (int'(item == 1)) >= 1;
    burst_len.sum() with (int'(item == 2 || item == 4)) >= 1;
    burst_len.sum() with (int'(item == 8)) >= 1;
    burst_len.sum() with (int'(item == 16)) >= 1;
  }


  // --------------------------------------------------------------------------
  // Constraint 8: weighted fault-mode selection
  //
  // These are relative weights, not guaranteed exact percentages or counts.
  // The selected mode is applied to the corresponding array element in
  // post_randomize().
  // --------------------------------------------------------------------------
  constraint weight_mode {
    foreach (fault[i])
      fault[i] dist {
        NO_ERROR    := 30,
        BAD_ADDRESS := 20,
        BAD_BURST   := 30,
        BAD_BEAT    := 20
      };
  }


  // --------------------------------------------------------------------------
  // post_randomize()
  //
  // Called automatically after a successful randomize().
  //
  // For each transaction:
  //   1. Copy the legal randomized fields into the drive arrays.
  //   2. Apply one selected mutation.
  //   3. Calculate transfer size and exclusive end address.
  //   4. Print and check the baseline values.
  //   5. Print and check the injected drive values.
  //
  // The original rand arrays are not modified by the error injection.
  // --------------------------------------------------------------------------
  function void post_randomize();

    int unsigned total_data;
    int unsigned end_addr;

    foreach (start_addr[i]) begin

      // Step 1: copy the legal baseline into the values intended for the driver.
      invalid_start_addr[i] = start_addr[i];
      invalid_burst_len[i]  = burst_len[i];
      invalid_beat_size[i]  = beat_size[i];


      // Step 2: inject the selected fault into exactly one drive field.
      case (fault[i])

        BAD_ADDRESS:
          invalid_start_addr[i] = 4099; // Invalid: address > 4095

        BAD_BURST:
          invalid_burst_len[i] = 7;     // Invalid: not in legal burst set

        BAD_BEAT:
          invalid_beat_size[i] = 3;     // Invalid: not in legal beat-size set

        NO_ERROR:
          ; // Keep all copied values unchanged

        default:
          ; // Defensive default; all declared enum values are covered above

      endcase


      // Step 3: calculate values from the legal baseline for accurate checking.
      total_data = burst_len[i] * beat_size[i];
      end_addr   = start_addr[i] + total_data;


      // ----------------------------------------------------------------------
      // Normal baseline report
      // ----------------------------------------------------------------------
      $display("\n========================== NORMAL_CASES ==========================");

      $display(
        "TXN[%0d] || START_ADDR=%0d || BURST_LEN=%0d || BEAT_SIZE=%0d"
        " || TOTAL_DATA=%0d || FAULT_TYPE=%s",
        i,
        start_addr[i],
        burst_len[i],
        beat_size[i],
        total_data,
        fault[i].name()
      );


      // Check that the baseline address is within the memory address range.
      if (start_addr[i] <= 4095)
        $display("PASS: Normal address is valid = %0d", start_addr[i]);
      else
        $display("FAIL: Normal address is out of range = %0d", start_addr[i]);


      // Check alignment of the legal baseline values.
      if (start_addr[i] % beat_size[i] == 0)
        $display("PASS: Normal address alignment is valid at index %0d", i);
      else
        $display("FAIL: Normal address alignment failed at index %0d", i);


      // Check the actual transfer end address, not just transfer size.
      if (end_addr <= 4096)
        $display(
          "PASS: Index=%0d, START_ADDR=%0d, END_ADDR=%0d, TOTAL_DATA=%0d",
          i, start_addr[i], end_addr, total_data
        );
      else
        $display("FAIL: Normal transfer exceeds memory at index %0d", i);


      // ----------------------------------------------------------------------
      // Error-injection report
      // ----------------------------------------------------------------------
      $display(
        "\n========================== ERROR_INJECTION_CASES =========================="
      );

      $display(
        "TXN[%0d] || DRIVE_ADDR=%0d || DRIVE_BURST_LEN=%0d"
        " || DRIVE_BEAT_SIZE=%0d || DRIVE_TOTAL_DATA=%0d || FAULT_TYPE=%s",
        i,
        invalid_start_addr[i],
        invalid_burst_len[i],
        invalid_beat_size[i],
        invalid_burst_len[i] * invalid_beat_size[i],
        fault[i].name()
      );


      // Check the address field in the drive-side transaction.
      if (invalid_start_addr[i] > 4095) begin
        if (fault[i] == BAD_ADDRESS)
          $display("PASS: BAD_ADDRESS injected = %0d", invalid_start_addr[i]);
        else
          $display("INFO: Drive address is out of range at index %0d", i);
      end
      else begin
        $display("INFO: Drive address remains in range at index %0d", i);
      end


      // Check alignment only when the injected beat size is itself legal.
      //
      // If beat size is 3, it is already an illegal beat-size injection.
      // Avoid treating modulo with an illegal value as the main validation.
      if (invalid_beat_size[i] inside {1, 2, 4}) begin

        if (invalid_start_addr[i] % invalid_beat_size[i] == 0)
          $display("PASS: Drive address is aligned at index %0d", i);
        else
          $display("INFO: Drive address is misaligned at index %0d", i);

      end
      else begin
        $display(
          "PASS: Illegal beat size injected at index %0d: %0d",
          i, invalid_beat_size[i]
        );
      end


      // Check whether the injected address/transfer size exceeds the memory.
      //
      // This is an informational boundary check because an injected BAD_BURST
      // or BAD_BEAT can change the transfer size as well.
      if ((invalid_start_addr[i] > 4095) ||
          (invalid_start_addr[i] +
           (invalid_burst_len[i] * invalid_beat_size[i]) > 4096)) begin

        $display("INFO: Injected transfer is outside memory range at index %0d", i);

      end
      else begin

        $display("INFO: Injected transfer remains within memory at index %0d", i);

      end


      // Check whether the injected burst length is outside the legal set.
      if (!(invalid_burst_len[i] inside {1, 2, 4, 8, 16})) begin

        if (fault[i] == BAD_BURST)
          $display("PASS: Illegal burst length injected = %0d",
                   invalid_burst_len[i]);
        else
          $display("INFO: Burst length is illegal at index %0d", i);

      end
      else begin

        $display("INFO: Drive burst length is legal at index %0d", i);

      end


      // Check whether the injected beat size is outside the legal set.
      if (!(invalid_beat_size[i] inside {1, 2, 4})) begin

        if (fault[i] == BAD_BEAT)
          $display("PASS: Illegal beat size injected = %0d",
                   invalid_beat_size[i]);
        else
          $display("INFO: Beat size is illegal at index %0d", i);

      end
      else begin

        $display("INFO: Drive beat size is legal at index %0d", i);

      end

    end // foreach (start_addr[i])

  endfunction : post_randomize

endclass : Memory_Burst_Transaction



// ============================================================================
// Testbench module
//
// Repeats randomization 10 times. Each successful randomization produces
// 16 transactions, giving 160 fault selections total.
//
// The counters are cumulative and are intentionally not reset inside repeat.
// ============================================================================
module tb;

  Memory_Burst_Transaction txn;

  int bad_addr_count;
  int bad_burst_count;
  int bad_beat_count;
  int normal_count;


  initial begin

    // Construct the transaction object. The constructor allocates invalid_*.
    txn = new();


    // Generate 10 batches of 16 transactions.
    repeat (10) begin

      // randomize() returns 1 on success and 0 on failure.
      if (!txn.randomize()) begin

        $error("Randomization failed");
        $finish;

      end


      // Count each fault mode for all 16 transaction entries in this batch.
      foreach (txn.fault[i]) begin

        case (txn.fault[i])

          NO_ERROR:
            normal_count++;

          BAD_ADDRESS:
            bad_addr_count++;

          BAD_BURST:
            bad_burst_count++;

          BAD_BEAT:
            bad_beat_count++;

          default:
            ; // No action for an unexpected enum value

        endcase

      end

    end // repeat


    // Print cumulative fault-mode counts across all randomizations.
    $display("\n==============================================");
    $display("FINAL ERROR DISTRIBUTION");
    $display("NORMAL       = %0d", normal_count);
    $display("BAD_ADDRESS  = %0d", bad_addr_count);
    $display("BAD_BURST    = %0d", bad_burst_count);
    $display("BAD_BEAT     = %0d", bad_beat_count);
    $display("TOTAL        = %0d",
             normal_count + bad_addr_count + bad_burst_count + bad_beat_count);
    $display("==============================================");

    $finish;

  end

endmodule : tb
